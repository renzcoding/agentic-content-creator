import json
import re
import urllib.request

from config.settings import OLLAMA_MODEL


def build_generation_prompt(content_brief: str) -> str:
    """Build a niche-aware generation prompt from the supplied content brief."""
    return f"""
You are a professional Indonesian short-form video scriptwriter.

CONTENT BRIEF:
{content_brief}

Requirements:
- Identify the exact topic, niche, audience, and content goal from the brief.
- Stay strictly on topic and follow the selected niche.
- Write natural, conversational Indonesian.
- Create one short hook directly related to the topic.
- Give exactly three practical points with different purposes.
- Each point must describe a concrete action, example, or useful insight.
- Adapt all points to the content niche and audience.
- Do not assume the content is about AI unless the brief explicitly says so.
- Do not repeat the same task, benefit, or example across points.
- Do not invent facts, statistics, quotes, or sources.
- End with one relevant CTA question.
- Keep the entire script between 60 and 85 words, including labels.
- Each numbered point must contain only one concise sentence.
- The CTA must contain only one short question.
- Do not use markdown formatting or quotation marks.
- Return only the finished script in the required format.

Format:
HOOK: One relevant opening sentence.
BODY:
1. First key point and explanation.
2. Second key point and explanation.
3. Third key point and explanation.
CTA: One relevant closing question.
""".strip()


def build_revision_prompt(
    script: str,
    issues: list[str],
    brief: str = "",
) -> str:
    """Build a revision prompt using the original brief and quality feedback."""
    return f"""
You are a concise Indonesian short-form video script editor.

CONTENT BRIEF:
{brief or "Use the topic and context from the original script."}

SCRIPT TO FIX:
{script}

QUALITY ISSUES:
{chr(10).join(issues)}

Instructions:
- Write in natural, concise Indonesian.
- Keep the complete script between 60 and 85 words, including labels.
- preserve the exact topic, niche, target audience from the original content brief.
- Retain the original content goal.
- Make all three BODY points specific and practical.
- Adapt the content to the original brief.
- Each BODY point must teach a different action, use case, or insight.
- Do not repeat the same task, benefit, or example across points.
- Do not assume the content is about AI unless the brief explicitly says so.
- Avoid generic claims without concrete explanations.
- Do not invent statistics or unsupported factual claims.
- Do not use markdown formatting.
- Return only the complete script without explanations or quotation marks.
- The CTA must be one complete question with at least 6 words.
- Ensure HOOK, BODY, and CTA are complete.
- Rewrite the entire script, not just individual sections.

Format:
HOOK: One short sentence.
BODY:
1. One practical point.
2. One practical point.
3. One practical point.
CTA: One short question.
""".strip()


def clean_script(script: str) -> str:
    """Remove placeholder labels generated by the model."""
    patterns = [
        r"\[Practical Point \d+\]\s*",
        r"\[Example\]\s*",
        r"\[Insert.*?\]\s*",
    ]

    for pattern in patterns:
        script = re.sub(pattern, "", script, flags=re.IGNORECASE)

    return script.strip()


def generate_script(content_brief: str) -> str:
    """Generate a niche-aware short-form video script using a local LLM."""
    payload = {
        "model": OLLAMA_MODEL,
        "prompt": build_generation_prompt(content_brief),
        "stream": False,
        "options": {
            "temperature": 0.3,
            "num_predict": 250,
        },
    }

    request = urllib.request.Request(
        "http://localhost:11434/api/generate",
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json"},
        method="POST",
    )

    with urllib.request.urlopen(request, timeout=300) as response:
        result = json.loads(response.read().decode("utf-8"))

    return clean_script(result["response"].strip())


def revise_script(
    script: str,
    issues: list[str],
    brief: str = "",
) -> str:
    """Revise a script using the original brief and quality feedback."""
    payload = {
        "model": OLLAMA_MODEL,
        "prompt": build_revision_prompt(script, issues, brief),
        "stream": False,
        "options": {
            "temperature": 0.1,
            "num_predict": 180,
        },
    }

    request = urllib.request.Request(
        "http://localhost:11434/api/generate",
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json"},
        method="POST",
    )

    try:
        with urllib.request.urlopen(request, timeout=300) as response:
            result = json.loads(response.read().decode("utf-8"))

        return clean_script(result["response"].strip())

    except Exception as error:
        print(f"Warning: Revision failed: {error}")
        return script


def trim_script(script: str) -> str:
    """Trim script sections to keep generated content concise."""
    limits = {
        "HOOK": 15,
        "BODY": 45,
        "CTA": 12,
    }

    sections = re.split(r"(?m)^(HOOK:|BODY:|CTA:)", script)
    if len(sections) < 7:
        return script

    result = []

    for index in range(1, len(sections), 2):
        label = sections[index]
        content = sections[index + 1].strip()
        words = content.split()

        if label == "BODY:":
            lines = content.splitlines()
            trimmed_lines = []
            remaining = limits["BODY"]

            for line in lines:
                line_words = line.split()
                if not line_words:
                    continue
                if len(line_words) > remaining:
                    line = " ".join(line_words[:remaining])
                    line = line.rstrip(" ,;:")
                trimmed_lines.append(line)
                remaining -= min(len(line_words), remaining)
                if remaining <= 0:
                    break

            content = "\n".join(trimmed_lines)
        else:
            content = " ".join(words[:limits[label[:-1]]])

        result.append(f"{label}\n{content}")

    return "\n".join(result)
